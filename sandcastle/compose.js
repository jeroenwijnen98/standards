// What a repo's Sandcastle setup is made of, from its two hand-written files:
// `.sandcastle/config.ts` (image, install commands, limits) and
// `.sandcastle/project.md` (the parts of the prompts only that repo knows).
// The prompts are composed at run time; the Dockerfile, .env.example and
// .gitignore are written by `sandcastle-setup sync`, because
// `sandcastle docker build-image` and the nightly run read them from disk.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const here = import.meta.dirname;

/** The sections a project.md may have, and the prompts each lands in. */
export const SECTIONS = ["Context", "Execution", "Checks", "Review", "Host only"];

export const PROMPTS = ["plan", "implement", "review", "merge"];

const GENERATED = "# Generated by sandcastle-setup from .sandcastle/config.ts:";

/** @param {string} repo */
export async function loadConfig(repo) {
  const file = join(repo, ".sandcastle/config.ts");
  const config = (await import(pathToFileURL(file).href)).default;
  return withDefaults(config);
}

/** @param {import("./index.d.ts").SandcastleConfig} config */
export function withDefaults(config) {
  if (!config?.image?.node) throw new Error(".sandcastle/config.ts: image.node is required");
  if (!Array.isArray(config.install)) {
    throw new Error(".sandcastle/config.ts: install is required ([] for none)");
  }
  return {
    maxIterations: 10,
    maxParallel: 3,
    model: "claude-opus-5-5",
    ...config,
    image: { apt: [], ...config.image },
  };
}

/**
 * Splits project.md into its `## ` sections. A heading it doesn't know is an
 * error, so a typo can't silently drop a section from every prompt.
 * @param {string} text
 */
export function parseProject(text) {
  /** @type {Record<string, string>} */
  const sections = {};
  for (const chunk of text.split(/^## /m).slice(1)) {
    const newline = chunk.indexOf("\n");
    const name = (newline === -1 ? chunk : chunk.slice(0, newline)).trim();
    if (!SECTIONS.includes(name)) {
      throw new Error(`.sandcastle/project.md: unknown section "## ${name}"; known: ${SECTIONS.join(", ")}`);
    }
    sections[name] = newline === -1 ? "" : chunk.slice(newline + 1).trim();
  }
  if (!sections.Checks) throw new Error(".sandcastle/project.md: a ## Checks section is required");
  return sections;
}

const CHECK_RULES = `Run every check in the foreground, and never start a test run while another is still
running. Save a full run's output (\`2>&1 | tee /tmp/<name>.log\`) and read that file again
instead of rerunning the suite.`;

/**
 * Step 3 of the merge: the sandbox installed its dependencies before the
 * merge, so a branch that added one is missing it there.
 * @param {{ command: string, when: string[] }[]} install
 */
function reinstallStep(install) {
  const runs = install
    .filter((step) => step.when.length > 0)
    .map((step) => `   - if the merge touched ${step.when.map((f) => `\`${f}\``).join(" or ")}, run \`${step.command}\``);
  if (runs.length === 0) return "3. This repo installs no dependencies, so a merge needs no reinstall.";
  return `3. The sandbox installed its dependencies *before* the merge, so a branch that added
   one is missing it here. An import error or \`Cannot find module\` after a merge is
   this, not a bug on the branch:
${runs.join("\n")}`;
}

/**
 * @param {string} name one of PROMPTS
 * @param {ReturnType<typeof withDefaults>} config
 * @param {Record<string, string>} project from parseProject
 */
export function composePrompt(name, config, project) {
  const template = readFileSync(join(here, "prompts", `${name}.md`), "utf8");
  return template
    .replace(/^<!-- project: (.+?) -->$/gm, (_, section) => {
      const body = project[section] ?? "";
      // Review adds bullets to the template's correctness list.
      return section === "Review" && body ? body.replace(/^(?=.)/gm, "   ") : body;
    })
    .replace("<!-- shared: check rules -->", CHECK_RULES)
    .replace("<!-- shared: reinstall -->", reinstallStep(config.install))
    .replace(/\n{3,}/g, "\n\n");
}

/** @param {ReturnType<typeof withDefaults>} config */
export function renderDockerfile(config) {
  const { node, python, apt, playwright, root, agent } = config.image;
  const packages = ["git", "curl", "jq", ...apt];
  const out = [
    `${GENERATED} edit that, then run`,
    "# `npx sandcastle-setup sync`.",
    "",
  ];

  if (python) {
    out.push(
      `# Node ${node}, copied from the official image into Python ${python}'s.`,
      `FROM node:${node}-bookworm-slim AS node`,
      `FROM python:${python}-bookworm`,
      "COPY --from=node /usr/local/bin/node /usr/local/bin/node",
      "COPY --from=node /usr/local/lib/node_modules /usr/local/lib/node_modules",
      "RUN ln -s ../lib/node_modules/npm/bin/npm-cli.js /usr/local/bin/npm \\",
      "  && ln -s ../lib/node_modules/npm/bin/npx-cli.js /usr/local/bin/npx",
    );
  } else {
    out.push(`FROM node:${node}-bookworm`);
  }

  out.push(
    "",
    "RUN apt-get update && apt-get install -y \\",
    ...packages.map((p) => `  ${p} \\`),
    "  && rm -rf /var/lib/apt/lists/*",
    "",
    "# GitHub CLI: the agents read, comment on and close issues with it.",
    "RUN curl -fsSL https://cli.github.com/packages/githubcli-archive-keyring.gpg \\",
    "  | dd of=/usr/share/keyrings/githubcli-archive-keyring.gpg \\",
    '  && echo "deb [arch=$(dpkg --print-architecture) signed-by=/usr/share/keyrings/githubcli-archive-keyring.gpg] https://cli.github.com/packages stable main" \\',
    "  | tee /etc/apt/sources.list.d/github-cli.list > /dev/null \\",
    "  && apt-get update && apt-get install -y gh \\",
    "  && rm -rf /var/lib/apt/lists/*",
  );

  if (playwright) {
    out.push(
      "",
      "# Playwright: keep the version in step with @playwright/test in package.json.",
      "# The agent has no root, so the system libraries must be in the image.",
      `ARG PLAYWRIGHT_VERSION=${playwright}`,
      "RUN npx -y playwright@${PLAYWRIGHT_VERSION} install-deps chromium \\",
      "  && rm -rf /var/lib/apt/lists/*",
    );
  }

  if (root) out.push("", root.trim());

  out.push(
    "",
    "# Build-args for UID/GID alignment: sandcastle docker build-image",
    "# defaults these to the host user's UID/GID so image-built files",
    "# and bind-mounted files share an owner without runtime chown.",
    "ARG AGENT_UID=1000",
    "ARG AGENT_GID=1000",
    "",
  );
  if (python) {
    out.push(
      "# The python image ships no non-root user, so create one at the host's UID/GID.",
      "RUN groupadd -o -g $AGENT_GID agent \\",
      "  && useradd -o -u $AGENT_UID -g $AGENT_GID -m -d /home/agent -s /bin/bash agent",
    );
  } else {
    out.push(
      '# Rename the base image\'s "node" user to "agent" and align UID/GID.',
      "RUN groupmod -o -g $AGENT_GID node && usermod -o -u $AGENT_UID -g $AGENT_GID -d /home/agent -m -l agent node",
    );
  }

  out.push(
    "USER ${AGENT_UID}:${AGENT_GID}",
    "",
    "# Claude Code, and anything else installed with --user, lands here.",
    'ENV PATH="/home/agent/.local/bin:$PATH"',
    "",
    "# Dependencies are not baked in: the onSandboxReady hook installs them from",
    "# the repo's lockfiles (`install` in config.ts), so the image cannot drift",
    "# from the repo.",
    "",
    "# A Bash command that outlives Claude Code's timeout (2 min by default) moves to",
    '# the background, and a headless agent then ends its turn "waiting to be',
    '# notified", losing its uncommitted work. The full check takes minutes: allow 9,',
    "# under Sandcastle's 10-minute idle timeout.",
    "ENV BASH_DEFAULT_TIMEOUT_MS=540000 BASH_MAX_TIMEOUT_MS=540000",
    "# A rerun of the full check on a tree it already passed returns at once",
    "# (checked-tree).",
    "ENV CHECKED_TREE_REUSE=1",
    "",
    "RUN curl -fsSL https://claude.ai/install.sh | bash",
  );

  if (playwright) {
    out.push(
      "",
      "# Chromium lands in /home/agent/.cache/ms-playwright, where the agent looks.",
      "RUN npx -y playwright@${PLAYWRIGHT_VERSION} install chromium",
    );
  }

  if (agent) out.push("", agent.trim());

  out.push(
    "",
    "WORKDIR /home/agent",
    "",
    "# In worktree sandbox mode, Sandcastle bind-mounts the git worktree at",
    "# /home/agent/workspace and makes it the working directory at container start.",
    'ENTRYPOINT ["sleep", "infinity"]',
    "",
  );
  return out.join("\n");
}

export const ENV_EXAMPLE = readFileSync(join(here, "files/env.example"), "utf8");

/** Lines .sandcastle/.gitignore must have; the repo may add its own. */
export const IGNORED = [".env", "logs/", "worktrees/"];

/**
 * The generated files that differ from what config.ts renders, or that are
 * missing. Empty means the setup is in sync.
 * @param {string} repo
 */
export async function staleFiles(repo) {
  const config = await loadConfig(repo);
  const dir = join(repo, ".sandcastle");
  const read = (/** @type {string} */ name) =>
    existsSync(join(dir, name)) ? readFileSync(join(dir, name), "utf8") : undefined;
  const stale = [];
  if (read("Dockerfile") !== renderDockerfile(config)) stale.push("Dockerfile");
  if (read(".env.example") !== ENV_EXAMPLE) stale.push(".env.example");
  const ignored = (read(".gitignore") ?? "").split("\n").map((line) => line.trim());
  if (!IGNORED.every((line) => ignored.includes(line))) stale.push(".gitignore");
  parseProject(read("project.md") ?? "");
  return stale;
}

/**
 * Writes the composed prompts where sandcastle reads them (and where
 * sandcastle-watch can), and returns their paths by name.
 * @param {string} repo
 * @param {ReturnType<typeof withDefaults>} config
 */
export function writePrompts(repo, config, dir = join(repo, ".sandcastle/logs/prompts")) {
  const project = parseProject(readFileSync(join(repo, ".sandcastle/project.md"), "utf8"));
  mkdirSync(dir, { recursive: true });
  /** @type {Record<string, string>} */
  const paths = {};
  for (const name of PROMPTS) {
    paths[name] = join(dir, `${name}.md`);
    writeFileSync(paths[name], composePrompt(name, config, project));
  }
  return paths;
}
